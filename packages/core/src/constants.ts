// Global constants.

/** An ellipsis: a gap in numbered lines, and text that is still to come. */
export const ELLIPSIS = '...';

/** Between the two ends of a line range, `12-20`. */
export const RANGE_DASH = '-';

/** Between the parts of a label, `Agent - running`. */
export const LABEL_SEPARATOR = ' - ';

/** To pointed code, and to a message going out in a trace. */
export const RIGHT_ARROW = '->';

/** A message coming in, in a trace. */
export const LEFT_ARROW = '<-';

/** After a playback speed, `1.0x`. */
export const SPEED_SUFFIX = 'x';

/** Milliseconds in a second. */
export const MS_PER_SECOND = 1000;

/** Seconds in a minute. */
const SECONDS_PER_MINUTE = 60;

/** Milliseconds in a minute. */
export const MS_PER_MINUTE = SECONDS_PER_MINUTE * MS_PER_SECOND;
